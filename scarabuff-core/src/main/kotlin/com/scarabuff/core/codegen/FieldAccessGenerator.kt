package com.scarabuff.core.codegen

import com.squareup.kotlinpoet.BOOLEAN
import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.INT
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.TypeSpec
import java.util.zip.CRC32

/**
 * Generates a small `internal` object in the `com.google.flatbuffers` package that tells whether
 * a table field is present, without decoding it.
 *
 * flatc's generated accessors don't offer this, and `Table`'s position and `__offset` are
 * `protected`, so code in other packages can't check it either. Java's `protected` also grants
 * package access, though, and Kotlin honors that, so code placed in `com.google.flatbuffers` can.
 * That avoids both reflection, which code shrinkers like R8 can break, and catching the exception
 * flatc's `<field>AsByteBuffer` throws for an absent field, which costs microseconds per call.
 *
 * The object is `internal` to the module, and its name includes a hash of the schema packages, so
 * two modules that both use scarabuff don't generate the same class.
 */
object FieldAccessGenerator {

    private const val PACKAGE = "com.google.flatbuffers"
    private val TABLE = ClassName(PACKAGE, "Table")

    /** The object's name for a set of schema packages, stable across builds. */
    fun className(packages: Collection<String>): ClassName {
        val crc = CRC32().apply { update(packages.sorted().joinToString(",").toByteArray()) }
        return ClassName(PACKAGE, "ScarabuffFieldAccess_%08x".format(crc.value))
    }

    fun generate(className: ClassName): FileSpec =
        FileSpec.builder(className.packageName, className.simpleName)
            .addType(
                TypeSpec.objectBuilder(className)
                    .addModifiers(KModifier.INTERNAL)
                    .addKdoc(
                        "Generated by scarabuff. Lives in `com.google.flatbuffers` so it can read `Table.__offset`, " +
                            "which is protected (and so package-visible)."
                    )
                    .addFunction(
                        FunSpec.builder("isPresent")
                            .addKdoc("Whether [table] has the field at [vtableOffset] (4 + 2 × the field's id).")
                            .addParameter("table", TABLE)
                            .addParameter("vtableOffset", INT)
                            .returns(BOOLEAN)
                            .addStatement("return table.__offset(vtableOffset) != 0")
                            .build()
                    )
                    .build()
            )
            .build()
}
